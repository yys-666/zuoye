using RecipeManagement.Core;

namespace RecipeManagement.Tests;

/// <summary>
/// Day 1 example tests covering dictionary construction. More tests are
/// added in the feature-specific test files as the implementation grows.
/// </summary>
public sealed class RecipeManagerTests
{
    [Fact]
    public void Constructor_BuildsRecipeDictionary()
    {
        var manager = CreateManager();
        Assert.Equal(2, manager.RecipeCount);
        Assert.Equal("Recipe A", manager.FindRecipe(10)?.Title);
    }

    [Fact]
    public void Constructor_ThrowsWhenCollectionArgumentIsNull()
    {
        Assert.Throws<ArgumentNullException>(() => new RecipeManager(null!));
    }

    private static RecipeManager CreateManager()
    {
        return new RecipeManager(new[]
        {
            new Recipe
            {
                Id = 10,
                Title = "Recipe A",
                Ingredients = new() { "1 apple" },
                Instructions = new() { "First step", "Second step" }
            },
            new Recipe
            {
                Id = 20,
                Title = "Recipe B"
            }
        });
    }
}
